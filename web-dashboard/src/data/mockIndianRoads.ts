export function computeStats(defects: RoadDefect[]): DashboardStats {
  const totalDefects = defects.length;
  let criticalCount = 0;
  let highCount = 0;
  let moderateCount = 0;
  let lowCount = 0;
  let newTodayCount = 0;
  let totalDepth = 0;
  let maxDepthCm = 0;
  let totalAsphaltKg = 0;
  let repairedCount = 0;

  for (const d of defects) {
    if (d.severity === 'Critical') criticalCount++;
    else if (d.severity === 'High') highCount++;
    else if (d.severity === 'Moderate') moderateCount++;
    else if (d.severity === 'Low') lowCount++;

    if (d.isNewToday) newTodayCount++;
    if (d.status === 'Repaired') repairedCount++;

    totalDepth += d.estimatedDepthCm;
    if (d.estimatedDepthCm > maxDepthCm) {
      maxDepthCm = d.estimatedDepthCm;
    }
    totalAsphaltKg += d.estimatedAsphaltKg || 50;
  }

  return {
    totalDefects,
    criticalCount,
    highCount,
    moderateCount,
    lowCount,
    newTodayCount,
    avgDepthCm: totalDefects > 0 ? Number((totalDepth / totalDefects).toFixed(1)) : 0,
    maxDepthCm: Number(maxDepthCm.toFixed(1)),
    totalAsphaltNeededTonnes: Number((totalAsphaltKg / 1000.0).toFixed(2)),
    repairedCount,
  };
}
